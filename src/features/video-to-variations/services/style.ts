/** The starting style guide for a new project. Users can change it; Claude follows it. Based on the Voogle edit demo reel. */
export const DEFAULT_STYLE = `# Style

## Pacing
- Open on the hook. The first spoken line must earn the next five seconds.
- Runs of 3-7 seconds, hard cuts. No transitions.
- Cut every pause longer than 0.4 seconds, every filler word and every retake (keep the last take).

## Captions
- 6 words at most per card, uppercase, white with a black outline.
- Emphasise at most one word per card: the word the speaker stresses or the key idea.

## Title card
- The hook, word for word, for the first 2-3 seconds.

## Length
- 30-60 seconds. End on a complete thought.
`;

export const MAX_STYLE_CHARS = 20_000;
